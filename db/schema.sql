-- Legacy finance system schema (Oracle Database Free, PDB FREEPDB1, schema FINANCE).
-- Run as the FINANCE user. Not re-runnable: drop the Docker volume to rebuild.
SET DEFINE OFF

-- ---------------------------------------------------------------------------
-- Customers: the finance-side copy of a Salesforce Account.
-- sf_account_id is the idempotency key for Salesforce -> finance upserts.
-- It is NULL for legacy customers that have not been migrated yet.
-- ---------------------------------------------------------------------------
CREATE SEQUENCE customer_code_seq START WITH 2000 NOCACHE;

CREATE TABLE customers (
  customer_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_code    VARCHAR2(20)  NOT NULL,
  sf_account_id    VARCHAR2(18),
  customer_name    VARCHAR2(255) NOT NULL,
  abn              VARCHAR2(11),
  email            VARCHAR2(255),
  phone            VARCHAR2(40),
  address_line     VARCHAR2(255),
  suburb           VARCHAR2(100),
  state_code       VARCHAR2(3),
  postcode         VARCHAR2(4),
  country_code     VARCHAR2(2)   DEFAULT 'AU' NOT NULL,
  status           VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  credit_limit     NUMBER(12,2)  DEFAULT 0 NOT NULL,
  created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  last_modified    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT customers_code_uk   UNIQUE (customer_code),
  CONSTRAINT customers_sfid_uk   UNIQUE (sf_account_id),
  CONSTRAINT customers_status_ck CHECK (status IN ('ACTIVE', 'ON_HOLD', 'CLOSED'))
);

-- ---------------------------------------------------------------------------
-- Invoices: synced finance -> Salesforce (Invoice__c, external id = invoice_number).
-- last_modified drives the watermark; the index keeps the poll query cheap.
-- ---------------------------------------------------------------------------
CREATE TABLE invoices (
  invoice_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number   VARCHAR2(20)  NOT NULL,
  customer_id      NUMBER        NOT NULL,
  invoice_date     DATE          NOT NULL,
  due_date         DATE          NOT NULL,
  amount_ex_gst    NUMBER(12,2)  NOT NULL,
  gst_amount       NUMBER(12,2)  NOT NULL,
  total_amount     NUMBER(12,2)  GENERATED ALWAYS AS (amount_ex_gst + gst_amount) VIRTUAL,
  amount_paid      NUMBER(12,2)  DEFAULT 0 NOT NULL,
  currency_code    VARCHAR2(3)   DEFAULT 'AUD' NOT NULL,
  status           VARCHAR2(10)  DEFAULT 'OPEN' NOT NULL,
  description      VARCHAR2(255),
  created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  last_modified    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT invoices_number_uk   UNIQUE (invoice_number),
  CONSTRAINT invoices_customer_fk FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
  CONSTRAINT invoices_status_ck   CHECK (status IN ('OPEN', 'PART_PAID', 'PAID', 'VOID'))
);

CREATE INDEX invoices_last_modified_ix ON invoices (last_modified);
CREATE INDEX invoices_customer_ix      ON invoices (customer_id);

-- ---------------------------------------------------------------------------
-- Payments: loaded from the nightly CSV. payment_ref makes the load idempotent,
-- so re-processing the same file cannot double-count a payment.
-- ---------------------------------------------------------------------------
CREATE TABLE payments (
  payment_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_ref      VARCHAR2(30)  NOT NULL,
  invoice_id       NUMBER        NOT NULL,
  amount           NUMBER(12,2)  NOT NULL,
  currency_code    VARCHAR2(3)   DEFAULT 'AUD' NOT NULL,
  payment_date     DATE          NOT NULL,
  payment_method   VARCHAR2(10)  NOT NULL,
  payer_name       VARCHAR2(255),
  source_file      VARCHAR2(255),
  loaded_at        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT payments_ref_uk     UNIQUE (payment_ref),
  CONSTRAINT payments_invoice_fk FOREIGN KEY (invoice_id) REFERENCES invoices (invoice_id),
  CONSTRAINT payments_amount_ck  CHECK (amount > 0),
  CONSTRAINT payments_method_ck  CHECK (payment_method IN ('EFT', 'BPAY', 'CARD', 'CHEQUE'))
);

-- ---------------------------------------------------------------------------
-- Integration support tables.
-- ---------------------------------------------------------------------------
CREATE TABLE sync_watermark (
  sync_name        VARCHAR2(50) PRIMARY KEY,
  last_value       TIMESTAMP    NOT NULL,
  updated_at       TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE integration_errors (
  error_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correlation_id   VARCHAR2(64),
  interface_name   VARCHAR2(50)  NOT NULL,
  record_key       VARCHAR2(100),
  error_type       VARCHAR2(100),
  error_message    VARCHAR2(4000),
  payload          CLOB,
  created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------------
-- Keep last_modified honest no matter who updates the row.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER customers_touch_trg
BEFORE UPDATE ON customers
FOR EACH ROW
BEGIN
  :NEW.last_modified := SYSTIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER invoices_touch_trg
BEFORE UPDATE ON invoices
FOR EACH ROW
BEGIN
  :NEW.last_modified := SYSTIMESTAMP;
END;
/

-- ---------------------------------------------------------------------------
-- upsert_customer: idempotent Salesforce Account -> finance customer.
-- Keyed on sf_account_id. Returns the customer id and what happened.
-- If two events for a new account race, the loser hits the unique key and
-- falls back to an update instead of failing.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE upsert_customer (
  p_sf_account_id IN  VARCHAR2,
  p_customer_name IN  VARCHAR2,
  p_abn           IN  VARCHAR2,
  p_email         IN  VARCHAR2,
  p_phone         IN  VARCHAR2,
  p_address_line  IN  VARCHAR2,
  p_suburb        IN  VARCHAR2,
  p_state_code    IN  VARCHAR2,
  p_postcode      IN  VARCHAR2,
  p_status        IN  VARCHAR2,
  p_credit_limit  IN  NUMBER,
  p_customer_id   OUT NUMBER,
  p_action        OUT VARCHAR2
) AS
  PROCEDURE do_update IS
  BEGIN
    UPDATE customers
       SET customer_name = p_customer_name,
           abn           = p_abn,
           email         = p_email,
           phone         = p_phone,
           address_line  = p_address_line,
           suburb        = p_suburb,
           state_code    = p_state_code,
           postcode      = p_postcode,
           status        = NVL(p_status, status),
           credit_limit  = NVL(p_credit_limit, credit_limit)
     WHERE sf_account_id = p_sf_account_id
    RETURNING customer_id INTO p_customer_id;
  END;
BEGIN
  IF p_sf_account_id IS NULL THEN
    RAISE_APPLICATION_ERROR(-20001, 'sf_account_id is required');
  END IF;

  do_update;
  IF SQL%ROWCOUNT > 0 THEN
    p_action := 'UPDATED';
    RETURN;
  END IF;

  BEGIN
    INSERT INTO customers (
      customer_code, sf_account_id, customer_name, abn, email, phone,
      address_line, suburb, state_code, postcode, status, credit_limit
    ) VALUES (
      'C' || LPAD(customer_code_seq.NEXTVAL, 6, '0'), p_sf_account_id, p_customer_name,
      p_abn, p_email, p_phone, p_address_line, p_suburb, p_state_code, p_postcode,
      NVL(p_status, 'ACTIVE'), NVL(p_credit_limit, 0)
    )
    RETURNING customer_id INTO p_customer_id;
    p_action := 'INSERTED';
  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      do_update;
      p_action := 'UPDATED';
  END;
END upsert_customer;
/

-- ---------------------------------------------------------------------------
-- apply_payment: record one payment and roll the invoice balance and status.
-- A payment_ref that already exists is reported as DUPLICATE, not an error.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE apply_payment (
  p_payment_ref    IN  VARCHAR2,
  p_invoice_number IN  VARCHAR2,
  p_amount         IN  NUMBER,
  p_currency_code  IN  VARCHAR2,
  p_payment_date   IN  DATE,
  p_payment_method IN  VARCHAR2,
  p_payer_name     IN  VARCHAR2,
  p_source_file    IN  VARCHAR2,
  p_result         OUT VARCHAR2,
  p_invoice_status OUT VARCHAR2
) AS
  v_invoice_id NUMBER;
  v_total      NUMBER;
  v_paid       NUMBER;
BEGIN
  BEGIN
    SELECT invoice_id, total_amount, amount_paid, status
      INTO v_invoice_id, v_total, v_paid, p_invoice_status
      FROM invoices
     WHERE invoice_number = p_invoice_number
       FOR UPDATE;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20002, 'Unknown invoice ' || p_invoice_number);
  END;

  IF p_invoice_status = 'VOID' THEN
    RAISE_APPLICATION_ERROR(-20003, 'Invoice ' || p_invoice_number || ' is void');
  END IF;

  BEGIN
    INSERT INTO payments (
      payment_ref, invoice_id, amount, currency_code, payment_date,
      payment_method, payer_name, source_file
    ) VALUES (
      p_payment_ref, v_invoice_id, p_amount, NVL(p_currency_code, 'AUD'), p_payment_date,
      p_payment_method, p_payer_name, p_source_file
    );
  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      p_result := 'DUPLICATE';
      RETURN;
  END;

  v_paid := v_paid + p_amount;
  p_invoice_status := CASE WHEN v_paid >= v_total THEN 'PAID' ELSE 'PART_PAID' END;

  UPDATE invoices
     SET amount_paid = v_paid,
         status      = p_invoice_status
   WHERE invoice_id = v_invoice_id;

  p_result := 'APPLIED';
END apply_payment;
/

-- ---------------------------------------------------------------------------
-- Reconciliation: one hash per migrated customer over the fields that sync.
-- The Mule reconciliation flow computes the same hash from Salesforce:
--   SHA-256 of  UPPER(TRIM(name)) | abn | LOWER(email) | postcode | status
-- with NULL treated as an empty string.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW v_customer_recon AS
SELECT sf_account_id,
       customer_code,
       LOWER(RAWTOHEX(STANDARD_HASH(
         UPPER(TRIM(customer_name)) || '|' || abn || '|' || LOWER(email) || '|' ||
         postcode || '|' || status, 'SHA256'))) AS row_hash,
       last_modified
  FROM customers
 WHERE sf_account_id IS NOT NULL;
